#!/usr/bin/env python3
"""Source-fold copies of the mask v4 training set, so the DeepLab wound mask can be scored on all 166 petchs sources.

DeepLab-v4 saw petchs train, and Roboflow copied each source photo across train/valid/test, so v4 cannot be scored on
the 166-source staging set. For fold k this keeps every non-petchs v4 training image as it is (FUSeg, CO2, DFUT,
segulcer), adds the petchs images of the *other* two source folds from all three splits (tissue polygons = open
surface, as in v4), and holds out every 6th remaining source plus the 20 Figshare ulcers for epoch selection -- the
same internal-validation sources as the tissue CNN folds. Pre-registered in HANDOFF (2026-10-30).

Training images that match a held-out petchs image under rotation/flip (dHash <= 6) are dropped.

    python -m training.prepare_deeplab_folds --fold 0 --out data/yolo_seg_v5_fold0
    python -m training.augment_tight_crops --dataset data/yolo_seg_v5_fold0 --copies 1 --seed 0
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import cv2
import numpy as np

from training.petchs_groups import RF_PETCHS, SPLITS, source, source_folds
from training.prepare_yolo_seg import _write_label, mask_to_polygons
from training.train_tissue_cnn import coco_items

V4 = Path("data/yolo_seg_v4")
_EXTS = {".jpg", ".jpeg", ".png", ".bmp", ".webp"}


def dhash_variants(bgr: np.ndarray) -> list[int]:
    """64-bit dHash of the image under the 8 rotations/flips."""
    g = cv2.cvtColor(bgr, cv2.COLOR_BGR2GRAY)
    out = []
    for flip in (False, True):
        a = g[:, ::-1] if flip else g
        for k in range(4):
            r = cv2.resize(np.ascontiguousarray(np.rot90(a, k)), (9, 8), interpolation=cv2.INTER_AREA).astype(np.int16)
            out.append(int("".join("1" if b else "0" for b in (r[:, 1:] > r[:, :-1]).flatten()), 2))
    return out


def dhash(bgr: np.ndarray) -> int:
    return dhash_variants(bgr)[0]


def _link(dst: Path, target: Path) -> None:
    if dst.exists() or dst.is_symlink():
        dst.unlink()
    dst.symlink_to(target.resolve())


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--fold", required=True, type=int)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--leak-hamming", type=int, default=6)
    args = ap.parse_args()
    for d in ("images", "labels"):
        for sp in ("train", "val"):
            (args.out / d / sp).mkdir(parents=True, exist_ok=True)

    folds = source_folds()
    keep = sorted(s for s, k in folds.items() if k != args.fold)
    val_src = set(keep[5::6])
    held_hashes: list[int] = []
    report = {"fold": args.fold, "petchs": {"train": 0, "val": 0, "no_tissue": 0}, "v4_kept": 0, "leak_dropped": []}

    for sp in SPLITS:
        for name, img, lab in coco_items(RF_PETCHS, sp):
            if folds[source(name)] == args.fold:
                held_hashes += dhash_variants(img)
                continue
            polys = mask_to_polygons(((lab >= 1) & (lab <= 3)).astype(np.uint8))
            if not polys:
                report["petchs"]["no_tissue"] += 1
                continue
            split = "val" if source(name) in val_src else "train"
            stem = f"petchs_{sp}_{Path(name).stem}"
            _link(args.out / "images" / split / f"{stem}{Path(name).suffix}", RF_PETCHS / sp / name)
            _write_label(args.out / "labels" / split / f"{stem}.txt", polys)
            report["petchs"][split] += 1

    def leaks(path: Path) -> bool:
        h = dhash(cv2.imread(str(path)))
        return any(bin(h ^ t).count("1") <= args.leak_hamming for t in held_hashes)

    for sp in ("train", "val"):
        for p in sorted((V4 / "images" / sp).iterdir()):
            if p.suffix.lower() not in _EXTS or "__crop" in p.stem or p.name.startswith("petchs_"):
                continue  # petchs comes from the fold split above; crops are regenerated by augment_tight_crops
            if sp == "val" and not p.name.startswith("figshare_"):
                continue
            if sp == "train" and leaks(p):
                report["leak_dropped"].append(p.name)
                continue
            _link(args.out / "images" / sp / p.name, p)
            _link(args.out / "labels" / sp / f"{p.stem}.txt", V4 / "labels" / sp / f"{p.stem}.txt")
            report["v4_kept"] += sp == "train"

    for p in (args.out / "images" / "train").iterdir():  # petchs training images vs the held-out fold, too
        if p.name.startswith("petchs_") and leaks(p):
            report["leak_dropped"].append(p.name)
            p.unlink()
            (args.out / "labels" / "train" / f"{p.stem}.txt").unlink()
            report["petchs"]["train"] -= 1

    (args.out / "data.yaml").write_text(
        f"path: {args.out.resolve()}\ntrain: images/train\nval: images/val\nnames:\n  0: wound\n")
    (args.out / "fold_report.json").write_text(json.dumps(report, indent=2))
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
